package indexstore

import (
	"bytes"
	"encoding/json"
	"slices"
)

// TranscriptPurge reports what one DropTranscriptTier did.
type TranscriptPurge struct {
	// LedgerLinesDropped is the recSession / recSuperseded / recFailure lines
	// the ledger rewrite removed.
	LedgerLinesDropped int
	// BaselineAdded is the archive source_sha256s added to the baseline set so
	// the automatic ingester's skip-list still covers them.
	BaselineAdded int
	// ChunksDropped is the chunks that had an archive owner before the purge.
	ChunksDropped int
	// KGDropped reports whether any KG record lost an archive owner.
	KGDropped bool
	// VectorsReaped is the orphaned *.vec files the reap removed.
	VectorsReaped int
}

// DropTranscriptTier removes every ARCHIVE-OWNED chunk, KG record and ledger
// session row from the project's store, leaving everything else in place. It
// is the one-time reclaim for a host that built the transcript tier before
// this host stopped indexing it; on a store with no archive owner it is a
// clean no-op.
//
// 🔴 THE LEDGER GOES FIRST, and this is the whole ordering argument, quoted
// from discardChunks, whose shape this follows: "Removed in any other order, a
// kill could leave a ledger that says an archive is ingested over a store that
// no longer holds its chunks, and search would answer from nothing without a
// word." After the ledger step every archive-owned chunk is OWNERLESS, and
// Store.Chunks(ledgeredOnly=true) skips a chunk with no live owner, so search
// stops seeing them at that instant even though their bytes are still on disk.
// Everything after the ledger step reclaims disk, nothing after it changes
// what search answers.
//
// 🔴 IT IS NOT Tx.Discard(DiscardChunks). That coarse path removes the ledger,
// chunks, KG and graph wholesale, which would destroy the OwnerBatch chunks
// and KG records the mempalace import wrote — and those are NOT re-derivable
// from the vault, unlike note-owned decision chunks (regenerated by the next
// build) and the notes / iterations / commit-log / drawer tiers (read from the
// vault on every walk). Preserving them is why the ledger is REWRITTEN rather
// than removed: recBatch lines are what internal/ingest's repair pass checks
// imported batches against, and the baseline records are the automatic
// ingester's skip-list.//
// 🔴 THE GUARANTEE IS SCOPED TO THIS OPERATION, AND SOMETHING ELSE ON THE SAME
// REBUILD CAN STILL DESTROY THAT DATA. `vp index rebuild <p> --drop-transcripts`
// runs step 3's discardOnMismatch FIRST, and a chunks-recipe mismatch there
// reaches Tx.Discard(DiscardChunks), whose coarse path removes ledger, chunks,
// KG and graph wholesale — the imported batches included. Nothing here protects
// that path, --drop-transcripts does not avoid it, and the purge that follows
// is then a clean no-op over an already-emptied store
// (TestThePurgeIsANoOpAfterACoarseDiscard). It is pre-existing ADR-014
// decision 3 behaviour and a separately filed defect, not something this
// operation solves.
//
// 🔴 freshBaseline is NOT called. It writes EVERY archive on disk into a NEW
// baseline record, which is discardChunks's call because discardChunks has
// just deleted the whole ledger and has nothing to preserve. Here the existing
// baseline history survives the rewrite, and the additive AddToBaseline covers
// the archives whose ownership this purge removed.
//
// otherLive is the reap's live set, exactly as Tx.Reap takes it.
//
// # Interruption
//
// Every write is atomic (writeFile is atomicfile.Write with fsync and
// dir-fsync), so no torn file exists, and re-running the purge finishes it:
// every step converges on the same FOLDED state. The counter is bumped
// explicitly immediately after the ledger write rather than left to Commit, so
// the window in which a lock-free, generation-keyed reader could pass an
// equal-generation witness over pre-write content is one counter write after
// one file write instead of the whole remainder of the Tx (a whole-file
// chunks.jsonl rewrite, the KG rewrite and the vector reap).
//
// 🔴 THAT IS A NARROWING, NOT A FIX, and this method claims nothing more. A
// kill landing strictly between the ledger write and the bump still leaves a
// reader able to conclude nothing changed. That window belongs to every
// destructive write in this package, not to this one, and it is filed as
// kill-between-generation-bumps-strands-lock-free-readers.
func (tx *Tx) DropTranscriptTier(otherLive func() (map[string]bool, error)) (TranscriptPurge, error) {
	var res TranscriptPurge
	if err := tx.fail(tx.beginDestructive()); err != nil {
		return res, err
	}

	// ---- step: purge-ledger -------------------------------------------
	// The graph first, inside this step: after a kill a reader that has not
	// yet loaded the graph finds none and installs nothing, rather than
	// serving a graph built over transcripts this purge is removing.
	if err := tx.fail(removeIfExists(tx.files.graph)); err != nil {
		return res, err
	}
	dropped, shas, err := tx.rewriteLedgerDroppingSessions()
	if err != nil {
		return res, tx.fail(err)
	}
	res.LedgerLinesDropped = dropped
	if dropped > 0 {
		// The bump, HERE, immediately after the ledger write — see the
		// interruption note above. bumpGenFile with a new epoch is the same
		// primitive beginDestructive uses, and tx.gen is updated as it does.
		g, berr := bumpGenFile(tx.genPath, true)
		if berr != nil {
			return res, tx.fail(berr)
		}
		tx.mu.Lock()
		tx.gen = g
		tx.wrote, tx.changeEpoch = true, true
		tx.mu.Unlock()
		// The rewrite changed the file under the Tx's cached view; drop it so
		// AddToBaseline below folds the ledger as it now is.
		tx.st = nil
	}
	if len(shas) > 0 {
		if err := tx.AddToBaseline(shas); err != nil {
			return res, err
		}
		res.BaselineAdded = len(shas)
	}
	if err := commitStep("purge-ledger"); err != nil {
		return res, tx.fail(err)
	}

	// ---- step: purge-chunks -------------------------------------------
	s, err := tx.state()
	if err != nil {
		return res, err
	}
	f, err := tx.chunkFold()
	if err != nil {
		return res, err
	}
	res.ChunksDropped = f.countOwnersOfKind(OwnerArchive)
	// ONE pass and ONE whole-file rewrite. Not ReplaceOwned(ArchiveOwner(sha),
	// nil) per archive, which is O(archives x store).
	changed := f.dropOwnersWhere(func(o Owner) bool { return o.Kind == OwnerArchive }, nil)
	if f.prune() {
		changed = true
	}
	if changed {
		if err := tx.fail(tx.writeChunkFold(s, f)); err != nil {
			return res, err
		}
	}
	if err := commitStep("purge-chunks"); err != nil {
		return res, tx.fail(err)
	}

	// ---- step: purge-kg -----------------------------------------------
	// 🔴 A SEPARATE PREDICATE ON A SEPARATE FUNCTION. kgFold.dropOwnersWhere
	// takes no keep map, unlike the chunk-side twin, and chunks and KG share
	// one BatchOwner — so a KG-side mistake here would destroy imported batch
	// KG with every chunk-side assertion green.
	k, err := tx.readKGFold()
	if err != nil {
		return res, err
	}
	if k.dropOwnersWhere(func(o Owner) bool { return o.Kind == OwnerArchive }) {
		res.KGDropped = true
		if err := tx.fail(tx.writeKGFold(s, k)); err != nil {
			return res, err
		}
	}
	if err := commitStep("purge-kg"); err != nil {
		return res, tx.fail(err)
	}

	// ---- step: purge-vectors ------------------------------------------
	// The orphaned *.vec files, through Reap's existing live-set path: the
	// pruned fold no longer holds their ids, so Reap removes exactly them.
	if otherLive != nil {
		reaped, rerr := tx.Reap(otherLive)
		if rerr != nil {
			return res, rerr
		}
		res.VectorsReaped = len(reaped)
	}
	if err := commitStep("purge-vectors"); err != nil {
		return res, tx.fail(err)
	}
	return res, nil
}

// rewriteLedgerDroppingSessions rewrites ledger.jsonl in place, keeping every
// recBaseline / recBaselineAdd / recBaselineClear / recBatch line BYTE FOR
// BYTE and dropping every recSession / recSuperseded / recFailure line. It
// returns how many lines it dropped and the archive source_sha256s those lines
// named.
//
// It edits RAW lines, as rewriteLedgerArchivePath does, so a kept line keeps
// every byte it had — including fields a newer binary wrote that this one does
// not model. A line this binary cannot parse at all is KEPT: dropping it would
// be a silent loss, and a kept unknown line is visible.
func (tx *Tx) rewriteLedgerDroppingSessions() (int, []string, error) {
	lines, _, _, err := readLines(tx.files.ledger)
	if err != nil {
		return 0, nil, err
	}
	out := make([][]byte, 0, len(lines))
	var shas []string
	dropped := 0
	for _, l := range lines {
		var rec ledgerRecord
		if json.Unmarshal(l, &rec) != nil {
			out = append(out, l) // unparseable: kept, never silently dropped
			continue
		}
		switch rec.Kind {
		case recSession, recSuperseded, recFailure:
			dropped++
			if rec.SHA != "" {
				shas = append(shas, rec.SHA)
			}
		default:
			out = append(out, l)
		}
	}
	slices.Sort(shas)
	shas = slices.Compact(shas)
	if dropped == 0 {
		return 0, shas, nil
	}
	var buf bytes.Buffer
	for _, l := range out {
		buf.Write(l)
		buf.WriteByte('\n')
	}
	if err := writeFile(tx.files.ledger, buf.Bytes()); err != nil {
		return 0, nil, err
	}
	tx.noteWrite(true)
	return dropped, shas, nil
}
